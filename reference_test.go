func referenceInputs() map[string][]byte {
	cases := map[string][]byte{}
	for _, n := range []int{1, 2, 3, 7, 8, 15, 64, 257, 258, 1535, 1536, 1537, 3071, 3072, 3073, 131071, 131072, 131073, 200000} {
		cases[fmt.Sprintf("zero-%d", n)] = make([]byte, n)
	}
	cases["hello"] = []byte("hello hello hello hello hello")
	cases["text"] = bytes.Repeat([]byte("LZHAM pure Go port: deterministic optimal parsing.\n"), 10000)
	cases["pattern"] = bytes.Repeat([]byte("abcdefghijklmnop"), 400)
	for _, n := range []int{256, 4096, 131072, 300000, 2200000} {
		data := make([]byte, n)
		rand.New(rand.NewSource(int64(n))).Read(data)
		cases[fmt.Sprintf("random-%d", n)] = data
	}
	mixed := make([]byte, 2200000)
	r := rand.New(rand.NewSource(42))
	for i := range mixed {
		mixed[i] = byte(r.Intn(10))
	}
	cases["mixed"] = mixed
	for seed := int64(0); seed < 64; seed++ {
		r := rand.New(rand.NewSource(seed + 27182))
		src := make([]byte, 32+int(seed)*211)
		alphabet := 2 + int(seed)%31
		for i := range src {
			src[i] = byte(r.Intn(alphabet))
		}
		cases[fmt.Sprintf("alphabet-%d", seed)] = src
	}
	for seed := int64(0); seed < 32; seed++ {
		r := rand.New(rand.NewSource(seed + 314159))
		src := make([]byte, 1000+int(seed)*509)
		period := 3 + int(seed)*7
		r.Read(src[:period])
		for i := period; i < len(src); i++ {
			src[i] = src[i-period]
			if r.Intn(23) == 0 {
				src[i] = byte(r.Intn(256))
			}
		}
		cases[fmt.Sprintf("mutated-%d", seed)] = src
	}
	switching := make([]byte, 3*dictSize+47)
	r = rand.New(rand.NewSource(1234))
	for i := range switching {
		switch i / (dictSize / 8) % 4 {
		case 0:
			switching[i] = byte(r.Intn(256))
		case 1:
			switching[i] = byte(i % 97)
		case 2:
			switching[i] = switching[i-dictSize/8]
		case 3:
			switching[i] = byte(r.Intn(4))
		}
	}
	cases["switching"] = switching
	return cases
}

// Golden values were frozen from the repository's original C++ memory API,
// not generated by this Go encoder. See testdata/oracle/README.md.
func TestReferenceCompression(t *testing.T) {
	type reference struct {
		Name         string
		SourceSHA256 string `json:"source_sha256"`
		Size         int
		SHA256       string
		Adler, CRC   uint32
		DecodedCRC   uint32 `json:"decoded_crc"`
	}
	var references []reference
	readReferenceJSON(t, "testdata/compress.json", &references)
	inputs := referenceInputs()
	if len(inputs) != len(references) {
		t.Fatalf("inputs=%d, reference cases=%d", len(inputs), len(references))
	}
	for _, tc := range references {
		t.Run(tc.Name, func(t *testing.T) {
			src, ok := inputs[tc.Name]
			if !ok || fmt.Sprintf("%x", sha256.Sum256(src)) != tc.SourceSHA256 {
				t.Fatal("reference input changed")
			}
			dst := bytes.Repeat([]byte{0xa5}, len(src)*2+1024)
			n, a, c, err := Compress(dst, src)
			if err != nil {
				t.Fatal(err)
			}
			if n != tc.Size || a != tc.Adler || c != tc.CRC || fmt.Sprintf("%x", sha256.Sum256(dst[:n])) != tc.SHA256 {
				t.Fatalf("C++ compression differs: size=%d, adler=%08x, crc=%08x, sha256=%x", n, a, c, sha256.Sum256(dst[:n]))
			}
			if !bytes.Equal(dst[n:], bytes.Repeat([]byte{0xa5}, len(dst)-n)) {
				t.Fatal("compress wrote beyond returned length")
			}
			got := make([]byte, len(src)+1)
			got[len(src)] = 0xa5
			m, a, c, err := Decompress(got, dst[:n])
			if err != nil || m != len(src) || a != tc.Adler || c != tc.DecodedCRC || !bytes.Equal(got[:m], src) || got[len(src)] != 0xa5 {
				t.Fatalf("C++ reference stream decode differs: size=%d, adler=%08x, crc=%08x, err=%v", m, a, c, err)
			}
		})
	}
}

func readReferenceJSON(t *testing.T, path string, dst interface{}) {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(data, dst); err != nil {
		t.Fatal(err)
	}
}
